import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {H0D_TOOL_ORDER} from "../scripts/h0d-tool-order.js";
const vals=Object.values(H0D_TOOL_ORDER);
assert.equal(vals.length,6);
assert.equal(new Set(vals).size,6,"Tous les outils doivent avoir un ordre distinct");
assert(vals.every(Number.isSafeInteger),"Les ordres doivent être des entiers stables");
assert(vals.every(x=>x>=100),"Utiliser des ordres réservés aux outils H0D");
const loot=readFileSync(new URL("../scripts/h0d-loot.js",import.meta.url),"utf8");
const tile=readFileSync(new URL("../scripts/h0d-merchant-tiles.js",import.meta.url),"utf8");
for(const name of ["loot","harvest","regenerate","merchant"]) assert(loot.includes("order: H0D_TOOL_ORDER."+name)||loot.includes("order:H0D_TOOL_ORDER."+name),name);
for(const name of ["merchantVisit","merchantTile"]) assert(tile.includes("order:H0D_TOOL_ORDER."+name),name);
assert(!/order:\s*Object\.keys\([^)]*tools\)\.length/.test(loot));
assert(!/order:\s*Object\.keys\([^)]*tools\)\.length/.test(tile));
assert(H0D_TOOL_ORDER.loot<H0D_TOOL_ORDER.harvest);
assert(H0D_TOOL_ORDER.harvest<H0D_TOOL_ORDER.regenerate);
assert(H0D_TOOL_ORDER.regenerate<H0D_TOOL_ORDER.merchant);
assert(H0D_TOOL_ORDER.merchant<H0D_TOOL_ORDER.merchantVisit);
console.log("Loot / Commerce : ordres Foundry stables et distincts.");
